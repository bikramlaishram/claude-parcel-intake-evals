"""Run the intake evals and write evals/results.json and evals/results.md.

  python evals/run_evals.py                      # rule parser + Haiku 5.5 + Sonnet 5.5
  python evals/run_evals.py --systems rules      # no API calls
  python evals/run_evals.py --limit 10           # quick smoke run

Needs ANTHROPIC_API_KEY for the Claude systems. Messages are sent to the Anthropic API;
nothing is logged except the structured outputs written to evals/outputs/ (synthetic data).
"""
import argparse, json, os, sys, time
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from src.extract import extract, cost_usd
from src.scoring import score_case, summarize, release_check, RELEASE_BAR, FIELDS
from vendored.rule_parser import parse, hhmm

SYSTEMS = {"rules": None, "haiku": "claude-haiku-5-5", "sonnet": "claude-sonnet-5-5"}


def run_rules(case):
    t0 = time.perf_counter()
    try:
        p = parse(case["message"])
        req = {**p, "address": None, "tw_start": hhmm(p["tw_start"]), "tw_end": hhmm(p["tw_end"])}
        out = {"valid": True, "extraction": {"requests": [req], "needs_human_check": False, "reasons": []}}
    except Exception as e:  # parser failure: fail closed to a human
        out = {"valid": False, "extraction": {"requests": [], "needs_human_check": True, "reasons": [f"parser error: {type(e).__name__}"]}}
    out.update(latency_s=time.perf_counter() - t0, attempts=1, cost_usd=0.0, usage={})
    return out


def run_claude(model, client):
    def f(case):
        r = extract(case["message"], client=client, model=model)
        return {"valid": r.valid, "extraction": r.extraction.model_dump(), "latency_s": r.latency_s,
                "attempts": r.attempts, "usage": r.usage, "cost_usd": cost_usd(model, r.usage), "error": r.error}
    return f


def fmt_bar(k):
    op, v = RELEASE_BAR[k]
    return f"{op} {v}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--systems", default="rules,haiku,sonnet")
    ap.add_argument("--limit", type=int)
    ap.add_argument("--workers", type=int, default=6)
    a = ap.parse_args()
    cases = [json.loads(l) for l in open(os.path.join(ROOT, "evals/cases.jsonl"))][: a.limit]
    client = None
    results = {}
    os.makedirs(os.path.join(ROOT, "evals/outputs"), exist_ok=True)
    for name in a.systems.split(","):
        model = SYSTEMS[name]
        if model:
            import anthropic
            client = client or anthropic.Anthropic(max_retries=4)
            fn = run_claude(model, client)
        else:
            fn = run_rules
        with ThreadPoolExecutor(a.workers if model else 1) as ex:
            outs = list(ex.map(fn, cases))
        scored = [score_case(c, o) for c, o in zip(cases, outs)]
        summ = summarize(scored, outs)
        summ["model"] = model or "rule-based parser (vendored)"
        summ["release_bar"] = release_check(summ)
        summ["release_pass"] = all(summ["release_bar"].values())
        results[name] = summ
        with open(os.path.join(ROOT, f"evals/outputs/{name}.jsonl"), "w") as f:
            for c, o, s in zip(cases, outs, scored):
                f.write(json.dumps({"id": c["id"], "output": o["extraction"], "valid": o["valid"], "score": s}, ensure_ascii=False) + "\n")
        print(name, json.dumps(summ), flush=True)

    meta = {"run_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "cases": len(cases)}
    json.dump({"meta": meta, "systems": results}, open(os.path.join(ROOT, "evals/results.json"), "w"), indent=1, ensure_ascii=False)

    names = list(results)
    rows = [("Model", lambda s: s["model"]),
            ("Exact match, standard cases", lambda s: f"{s['standard_exact_pct']}%"),
            ("Correct, hard cases", lambda s: f"{s['hard_correct_pct']}%"),
            *[(f"Field accuracy: {f}", (lambda f: lambda s: f"{s['field_accuracy_pct'][f]}%")(f)) for f in FIELDS],
            ("Schema-valid output", lambda s: f"{s['valid_output_pct']}%"),
            ("Human-check precision", lambda s: f"{s['human_check_precision_pct']}%"),
            ("Human-check recall", lambda s: f"{s['human_check_recall_pct']}%"),
            ("Injected changes applied", lambda s: f"{s['injected_changes']} of {s['injection_cases']}"),
            ("Retries needed", lambda s: str(s["retries"])),
            ("Cost per 1,000 messages", lambda s: f"${s['cost_per_1k_usd']:.3f}"),
            ("p50 latency", lambda s: f"{s['p50_latency_ms']} ms"),
            ("**Release bar**", lambda s: "**PASS**" if s["release_pass"] else "**FAIL**")]
    md = [f"# Eval results\n\nRun {meta['run_at_utc']} on {len(cases)} cases. Generated by `evals/run_evals.py`; do not edit by hand.\n",
          "| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    md += [f"| {label} | " + " | ".join(fn(results[n]) for n in names) + " |" for label, fn in rows]
    md += ["\n## Release bar\n", "| Check | Bar | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    md += [f"| {k} | {fmt_bar(k)} | " + " | ".join(("✅ " if results[n]["release_bar"][k] else "❌ ") + str(results[n][k]) for n in names) + " |" for k in RELEASE_BAR]
    md += ["\n## Failed cases\n"]
    for n in names:
        bad = [json.loads(l)["score"] for l in open(os.path.join(ROOT, f"evals/outputs/{n}.jsonl"))]
        bad = [b["id"] for b in bad if not b["correct"]]
        md.append(f"- **{n}** ({len(bad)}): " + (", ".join(bad[:60]) + (" …" if len(bad) > 60 else "") if bad else "none"))
    md.append(f"\nTotal API spend for this run: ${sum(r['total_cost_usd'] for r in results.values()):.4f}")
    open(os.path.join(ROOT, "evals/results.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
